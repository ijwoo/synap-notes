CREATE TABLE space_invite (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    space_id   BIGINT NOT NULL REFERENCES space(id) ON DELETE CASCADE,
    inviter_id BIGINT NOT NULL REFERENCES app_user(id),
    invitee_id BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE,
    status     TEXT NOT NULL DEFAULT 'pending',
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (space_id, invitee_id)
);

CREATE INDEX idx_space_invite_invitee ON space_invite (invitee_id, status);
