CREATE TABLE notification (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT NOT NULL REFERENCES app_user(id) ON DELETE CASCADE, -- 수신자
    type       TEXT NOT NULL,            -- comment | invite
    actor_name TEXT,                     -- 행위자 이름(비정규화)
    message    TEXT NOT NULL,            -- 표시 문구
    link       TEXT,                     -- 클라이언트 라우트 (예: /notes/12)
    read       BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

CREATE INDEX idx_notification_user ON notification (user_id, id DESC);
