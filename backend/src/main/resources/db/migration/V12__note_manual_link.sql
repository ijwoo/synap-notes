-- 사용자가 의도적으로 잇는 수동 링크 (자동 임베딩 링크 note_link 와 별개 — 재임베딩에 안 지워짐)
CREATE TABLE note_manual_link (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    note_id    BIGINT NOT NULL REFERENCES note(id) ON DELETE CASCADE,
    target_id  BIGINT NOT NULL REFERENCES note(id) ON DELETE CASCADE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now(),
    UNIQUE (note_id, target_id)
);

CREATE INDEX idx_manual_link_note ON note_manual_link (note_id);
CREATE INDEX idx_manual_link_target ON note_manual_link (target_id);
